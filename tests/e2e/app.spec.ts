    expect(await title()).toBe('King Chrum'); await expect(p.locator('#mHist')).toHaveCount(0)
    // Backspace / Alt+← go back one level; Esc still closes and clears the stack
    await p.locator('#mBody .prow .mini').first().click(); await p.locator('#mBody .mini').filter({ hasNotText: 'Token' }).filter({ hasNotText: pairName }).first().click()
    await expect(p.locator('#mHist .crumb')).toHaveCount(2)
    await p.keyboard.press('Backspace'); expect(await title()).toBe(pairName)
    await p.keyboard.press('Alt+ArrowLeft'); expect(await title()).toBe('King Chrum')
    await p.locator('#mBody .prow .mini').first().click(); await expect(p.locator('#mBack')).toBeVisible()
    await p.keyboard.press('Escape'); await expect(p.locator('#mback')).toBeHidden()
    await p.locator('#grid .gc .name').first().click()
    await expect(p.locator('#mTitle')).toContainText('King Chrum'); await expect(p.locator('#mHist')).toHaveCount(0)
    await p.keyboard.press('Backspace'); await expect(p.locator('#mTitle')).toContainText('King Chrum')
